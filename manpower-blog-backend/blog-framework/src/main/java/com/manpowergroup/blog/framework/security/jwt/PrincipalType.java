package com.manpowergroup.blog.framework.security.jwt;

/**
 * 認証主体の種別。
 *
 * <p>運用者と会員は認証経路・権限体系・採番系列のいずれも共有しない。
 * 会員はポータルから自己登録できるため、有効な署名を持つトークンの取得コストは
 * 実質ゼロである。両者を区別せずに同一の検証経路へ流すと、
 * 会員 #1 のトークンが運用者 #1 として解釈され得る。</p>
 *
 * <p>本 enum は「どの面のトークンか」だけを表す。
 * ロールや権限といった業務上の区分は含まない。</p>
 */
public enum PrincipalType {

    /** 運用者（t_sys_user）。管理画面を利用する。 */
    USER,

    /** 会員（t_member）。ポータルから自己登録する。 */
    MEMBER
}
